/** The pixel width of `text` at one glyph per 6 columns. */
export const textWidth = (text) => [...text].length * 6 - 1;

/** Calls set(x, y) for each lit pixel of `text`, with (x, y) the top-left. */
export function drawText(text, x, y, set) {
  let cx = x;
  for (const ch of text) {
    const g = G[ch] ?? G[ch.toLowerCase()] ?? G[" "];
    g.forEach((row, ry) => {
      for (let rx = 0; rx < 5; rx++) if (row[rx] === "#") set(cx + rx, y + ry);
    });
    cx += 6;
  }
}
