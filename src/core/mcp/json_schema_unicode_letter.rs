/// Returns true when `codepoint` has the Unicode `Letter` property
/// (General Categories Lu, Ll, Lt, Lm, Lo) in Unicode 13.0.
pub fn contains(codepoint: char) -> bool {
    let cp = codepoint as u32;
    let mut low = 0usize;
    let mut high = RANGES.len();
    while low < high {
        let middle = low + (high - low) / 2;
        let range = &RANGES[middle];
        if cp < range.first {
            high = middle;
        } else if cp > range.last {
            low = middle + 1;
        } else {
            return true;
        }
    }
    false
}

